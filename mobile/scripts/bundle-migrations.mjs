// Inlines drizzle/*.sql and the journal into src/db/migrations.ts, the
// shape drizzle-orm/expo-sqlite's migrate() expects. Run by
// `pnpm run db:generate`; commit the result.
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8"));

const migrations = {};
for (const entry of journal.entries) {
  migrations[`m${String(entry.idx).padStart(4, "0")}`] = readFileSync(join(root, "drizzle", `${entry.tag}.sql`), "utf8");
}

writeFileSync(
  join(root, "src/db/migrations.ts"),
  `// Generated by scripts/bundle-migrations.mjs from drizzle/. Do not edit.
export const migrations = ${JSON.stringify({ journal, migrations }, null, 2)};
`,
);
console.log(`Bundled ${journal.entries.length} migration(s) into src/db/migrations.ts`);

// drizzle-kit's own expo output imports the .sql files directly, which Metro
// can't load without extra config; the file above replaces it.
rmSync(join(root, "drizzle/migrations.js"), { force: true });
